#!/usr/bin/env python3
"""Render small lit-sphere thumbnails of the Sun, Moon and planets from the 3D-view maps
(public/textures3d) and write them as data URIs to src/planet-thumbs.ts, so the Tonight
bars, search results and object cards show real surfaces instead of flat dots."""
import base64, io, math, pathlib
import numpy as np
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
TEX = ROOT / "public" / "textures3d"
OUT = ROOT / "src" / "planet-thumbs.ts"
SIZE, SS = 72, 4  # output px, supersampling


def sphere(map_name: str, lon0: float, lat0: float, radius: float, lit_sun: bool = False) -> Image.Image:
    """A lit globe from a square crop of the map centred on (lon0, lat0), with a mild
    spherical bulge so features curve toward the limb. At thumbnail size this reads better
    than a true orthographic projection, which smears every map into mirrored streaks."""
    n = SIZE * SS
    img = Image.open(TEX / f"{map_name}.jpg").convert("RGB")
    W, H = img.size
    span = 120  # degrees of the map shown across the disc
    side = int(W * span / 360)
    cx, cy = int((lon0 / 360 + 0.5) * W), int((0.5 - lat0 / 180) * H)
    box = (cx - side // 2, max(0, min(H - side, cy - side // 2)))
    crop = Image.new("RGB", (side, side))
    for dx in (0, 1):  # wrap around the 180th meridian
        crop.paste(img.crop((box[0] - dx * W, box[1], box[0] + side - dx * W, box[1] + side)), (0, 0)) if (0 <= box[0] - dx * W + side and box[0] - dx * W < W) else None
    tex = np.asarray(crop.resize((n, n), Image.LANCZOS), dtype=np.float32)
    axis = ((np.arange(n, dtype=np.float64) + 0.5 - n / 2) / (n / 2 * radius))
    x = np.broadcast_to(axis[None, :], (n, n)).copy()
    y = np.broadcast_to(-axis[:, None], (n, n)).copy()
    r2 = np.square(x) + np.square(y)
    inside = r2 <= 1
    z = np.sqrt(np.clip(1 - r2, 0, 1))
    # bulge: sample coordinates spread out toward the limb (monotonic in x and y)
    k = 0.35
    f = (1 + k * (1 - z)) / (1 + k)
    sx = np.clip(((x * f + 1) / 2) * (n - 1), 0, n - 1).astype(int)
    sy = np.clip(((-y * f + 1) / 2) * (n - 1), 0, n - 1).astype(int)
    px = tex[sy, sx]
    if lit_sun:
        shade = 0.6 + 0.4 * z ** 0.6
    else:
        lx, ly, lz = -0.45, 0.5, 0.74
        shade = np.clip(x * lx + y * ly + z * lz, 0, 1) * 0.85 + 0.15
    rgb = px * shade[..., None]
    out = np.dstack([rgb.clip(0, 255), inside.astype(np.float32) * 255]).astype(np.uint8)
    return Image.fromarray(out)


def with_rings(planet: Image.Image) -> Image.Image:
    """Saturn: shrink the globe and add a tilted ring, back half behind, front half over."""
    n = planet.width
    globe = planet.resize((int(n * 0.62), int(n * 0.62)), Image.LANCZOS)
    canvas_back = Image.new("RGBA", (n, n))
    canvas_front = Image.new("RGBA", (n, n))
    cx = cy = n / 2
    tilt = math.radians(-20)
    ct, st = math.cos(tilt), math.sin(tilt)
    arr_b = np.zeros((n, n, 4), np.uint8)
    arr_f = np.zeros((n, n, 4), np.uint8)
    ys, xs = np.mgrid[0:n, 0:n].astype(np.float32)
    dx, dy = xs - cx, ys - cy
    ex, ey = dx * ct + dy * st, -dx * st + dy * ct  # into ring frame
    A, B = n * 0.49, n * 0.49 * 0.30
    q = np.sqrt((ex / A) ** 2 + (ey / B) ** 2)
    inner, outer = 0.62, 1.0
    ring = (q >= inner) & (q <= outer)
    gap = (q > 0.84) & (q < 0.88)  # Cassini division
    t = (q - inner) / (outer - inner)
    shade = 0.75 + 0.25 * np.sin(t * 18)
    col = np.dstack([232 * shade, 208 * shade, 160 * shade])
    a = np.where(ring & ~gap, 235, 0)
    px = np.dstack([col, a]).astype(np.uint8)
    front = ey > 0
    arr_b[~front] = px[~front]
    arr_f[front] = px[front]
    back, fr = Image.fromarray(arr_b), Image.fromarray(arr_f)
    out = Image.new("RGBA", (n, n))
    out.alpha_composite(back)
    out.alpha_composite(globe, (int((n - globe.width) / 2), int((n - globe.height) / 2)))
    out.alpha_composite(fr)
    return out


BODIES = {
    "Sun": ("sun", 0, 0, 1.0, True),
    "Moon": ("moon", 0, 0, 1.0, False),
    "Mercury": ("mercury", 20, 0, 1.0, False),
    "Venus": ("venus", 0, 0, 1.0, False),
    "Mars": ("mars", 300, 5, 1.0, False),  # Syrtis Major side, reads as "Mars"
    "Jupiter": ("jupiter", 0, 0, 1.0, False),
    "Saturn": ("saturn", 0, 0, 1.0, False),
    "Uranus": ("uranus", 0, 0, 1.0, False),
    "Neptune": ("neptune", 0, 0, 1.0, False),
}


def data_uri(img: Image.Image) -> str:
    img = img.resize((SIZE, SIZE), Image.LANCZOS)
    buf = io.BytesIO()
    img.save(buf, "PNG", optimize=True)
    return "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()


lines = ["/** Generated by scripts/make-planet-thumbs.py from public/textures3d (CC BY 4.0, Solar System Scope). */",
         "export const PLANET_THUMBS: Record<string, string> = {"]
for name, (m, lo, la, rad, sun) in BODIES.items():
    img = sphere(m, lo, la, rad, sun)
    if name == "Saturn":
        img = with_rings(img)
    lines.append(f'  {name}: "{data_uri(img)}",')
lines.append("};")
OUT.write_text("\n".join(lines) + "\n")
print("wrote", OUT, OUT.stat().st_size // 1024, "KB")
